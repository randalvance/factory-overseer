import { expect, test } from "@playwright/test"

test("initial requests notify once through StrictMode, rerenders and callback replacement", async ({ page }) => {
  const errors: string[] = []
  page.on("pageerror", (error) => errors.push(error.message))
  await page.goto("/e2e/fixtures/human-needed.html")
  const notifications = page.getByRole("list", { name: "Notifications" }).getByRole("listitem")
  await expect(notifications).toHaveText(["request-1 callback 0"])
  await page.getByRole("button", { name: "Repeat snapshot", exact: true }).click()
  await page.getByRole("button", { name: "Replace callback", exact: true }).click()
  await expect(notifications).toHaveCount(1)
  await expect(page.getByRole("alert")).toHaveCount(0)
  await page.getByRole("button", { name: "Resolve", exact: true }).click()
  await page.getByRole("button", { name: "Replay old request", exact: true }).click()
  await expect(notifications).toHaveCount(1)
  await page.getByRole("button", { name: "Next question", exact: true }).click()
  await expect(notifications).toHaveText(["request-1 callback 0", "request-2 callback 1"])
  await expect(page.getByLabel("Task room")).toHaveText("planning")
  await page.getByRole("button", { name: "Invalid request", exact: true }).click()
  await expect(page.getByRole("alert")).toContainText("Unknown room")
  await expect(notifications).toHaveCount(2)
  expect(errors).toEqual([])
})

test("optional handlers, concurrent requests and remounts follow the notification contract", async ({ page }) => {
  await page.goto("/e2e/fixtures/human-needed.html?no-handler")
  const notifications = page.getByRole("list", { name: "Notifications" }).getByRole("listitem")
  await expect(page.getByRole("img", { name: "Factory floor" })).toHaveAttribute("data-drawn", "1")
  await expect(notifications).toHaveCount(0)
  await page.getByRole("button", { name: "Enable handler", exact: true }).click()
  await expect(notifications).toHaveCount(1)
  await page.getByRole("button", { name: "Concurrent requests", exact: true }).click()
  await expect(notifications).toHaveText(["request-1 callback 0", "request-2 callback 0", "approval-1 callback 0", "help-1 callback 0"])
  await page.getByRole("button", { name: "Disable handler", exact: true }).click()
  await page.getByRole("button", { name: "Enable handler", exact: true }).click()
  await expect(notifications).toHaveCount(4)
  await page.getByRole("button", { name: "Remount", exact: true }).click()
  await expect(notifications).toHaveCount(7)
})

test("planning asks two questions and holds work until the host resolves them", async ({ page }) => {
  test.setTimeout(60000)
  const errors: string[] = []
  page.on("pageerror", (error) => errors.push(error.message))
  page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()) })
  await page.goto("/")
  await expect(page.getByRole("img", { name: "Factory floor" })).toHaveAttribute("data-drawn", "1")
  await page.getByRole("slider", { name: "Speed" }).fill("8")
  await page.getByRole("button", { name: "Send to Planning", exact: true }).click()
  const first = page.getByRole("form", { name: "Who is this feature for, and what should it do?" })
  await expect(first).toBeVisible({ timeout: 30000 })
  await expect(page.getByRole("button", { name: "Send to Implementation", exact: true })).toBeDisabled()
  await page.getByRole("slider", { name: "Speed" }).fill("2")
  await expect(page.getByRole("form")).toHaveCount(1)
  await page.screenshot({ path: "test-results/human-needed.png" })
  await first.getByRole("textbox", { name: "Your response" }).fill("Factory operators need to see their tasks.")
  await first.getByRole("button", { name: "Submit response", exact: true }).click()
  const second = page.getByRole("form", { name: "What should count as success, and which constraints matter?" })
  await expect(second).toBeVisible()
  await expect(first).toHaveCount(0)
  await expect(page.getByRole("button", { name: "Send to Implementation", exact: true })).toBeDisabled()
  await second.getByRole("textbox", { name: "Your response" }).fill("Show both task routes while keeping agents visible.")
  await second.getByRole("button", { name: "Submit response", exact: true }).click()
  await expect(page.getByRole("form")).toHaveCount(0)
  await expect(page.getByRole("status")).toContainText("in Planning")
  await expect(page.getByRole("status")).not.toContainText("waiting for your response")
  await expect(page.getByRole("button", { name: "Send to Implementation", exact: true })).toBeEnabled()
  await page.getByRole("slider", { name: "Speed" }).fill("8")
  await page.getByRole("button", { name: "Send to Implementation", exact: true }).click()
  await expect(page.getByRole("status")).toContainText("in Implementation", { timeout: 30000 })
  await page.getByRole("button", { name: "Ask for help", exact: true }).click()
  await expect(page.getByRole("form", { name: "What help or clarification does this task need?" })).toBeVisible()
  await expect(page.getByRole("button", { name: "Send to Code review", exact: true })).toBeDisabled()
  expect(errors).toEqual([])
})
