import { expect, test } from "@playwright/test"

test("planning, direct implementation, rework and deployment follow configured conveyors", async ({ page }) => {
  test.setTimeout(120000)
  const errors: string[] = []
  page.on("pageerror", (error) => errors.push(error.message))
  page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()) })
  await page.goto("/")
  await expect(page.getByRole("img", { name: "Factory floor" })).toHaveAttribute("data-drawn", "1")
  await page.screenshot({ path: "test-results/routes-opening.png" })
  await page.getByRole("slider", { name: "Speed" }).fill("8")
  const status = page.getByRole("status")
  async function send(button: string, room: string) {
    await page.getByRole("button", { name: button, exact: true }).click()
    await expect(status).toContainText("riding to " + room, { timeout: 10000 })
    await expect(status).toContainText("in " + room, { timeout: 30000 })
    await expect(page.getByRole("alert")).toHaveCount(0)
  }
  await send("Send to Planning", "Planning")
  await send("Send to Implementation", "Implementation")
  await send("Return to planning", "Planning")
  await send("Send to Implementation", "Implementation")
  await page.getByRole("combobox", { name: "Task", exact: true }).selectOption("task-2")
  await send("Send to Implementation", "Implementation")
  await send("Send to Code review", "Code review")
  await send("Send to Deployment", "Deployment")
  await page.getByRole("button", { name: "Ship task", exact: true }).click()
  await expect(status).toContainText("shipped from Deployment", { timeout: 30000 })
  await expect(page.getByLabel("Counts")).toContainText("1 shipped")
  await page.screenshot({ path: "test-results/routes-deployment.png" })
  expect(errors).toEqual([])
})

test("unstaffed queues, an added QA room and live connection removal remain routable", async ({ page }) => {
  test.setTimeout(120000)
  const errors: string[] = []
  page.on("pageerror", (error) => errors.push(error.message))
  page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()) })
  await page.goto("/")
  await expect(page.getByRole("img", { name: "Factory floor" })).toHaveAttribute("data-drawn", "1")
  await page.getByRole("slider", { name: "Speed" }).fill("8")
  await page.getByRole("button", { name: "Unstaff planning", exact: true }).click()
  await page.getByRole("button", { name: "Send to Planning", exact: true }).click()
  await expect(page.getByRole("status")).toContainText("in Planning · waiting for assignment", { timeout: 30000 })
  await page.getByRole("button", { name: "Staff planning", exact: true }).click()
  await expect(page.getByRole("status")).not.toContainText("waiting for assignment")
  await expect(page.getByRole("button", { name: "Send to Implementation", exact: true })).toBeEnabled({ timeout: 30000 })
  await page.getByRole("combobox", { name: "Task", exact: true }).selectOption("task-2")
  await page.getByRole("slider", { name: "Speed" }).fill("2")
  await page.getByRole("button", { name: "Send to Implementation", exact: true }).click()
  await expect(page.getByRole("status")).toContainText("riding to Implementation")
  await page.getByRole("button", { name: "Remove bypass", exact: true }).click()
  await page.getByRole("button", { name: "Add agent", exact: true }).click()
  await page.getByRole("slider", { name: "Speed" }).fill("8")
  await expect(page.getByRole("status")).toContainText("in Implementation", { timeout: 30000 })
  await page.getByRole("button", { name: "Include QA room", exact: true }).click()
  await page.getByRole("button", { name: "Send to Code review", exact: true }).click()
  await expect(page.getByRole("status")).toContainText("in Code review", { timeout: 30000 })
  await page.getByRole("button", { name: "Send to QA", exact: true }).click()
  await expect(page.getByRole("status")).toContainText("in QA · waiting for assignment", { timeout: 30000 })
  await page.screenshot({ path: "test-results/routes-qa.png" })
  await expect(page.getByRole("alert")).toHaveCount(0)
  expect(errors).toEqual([])
})
