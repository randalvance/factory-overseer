import { expect, test } from "@playwright/test"

test("shared work waits for both participants, survives human help and rework, and joins explicitly", async ({ page }) => {
  test.setTimeout(120000)
  const errors: string[] = []
  page.on("pageerror", (error) => errors.push(error.message))
  await page.goto("/")
  await expect(page.getByRole("img", { name: "Factory floor" })).toHaveAttribute("data-drawn", "1")
  await page.getByRole("slider", { name: "Speed" }).fill("8")
  await page.getByRole("combobox", { name: "Task", exact: true }).selectOption("task-2")
  await page.getByRole("button", { name: "Send to Implementation", exact: true }).click()
  await expect(page.getByRole("status")).toContainText("in Implementation", { timeout: 30000 })
  await page.getByRole("button", { name: "Assign two implementers" }).click()
  const shared = page.getByRole("region", { name: "Shared implementation" })
  const review = page.getByRole("button", { name: "Send to Code review", exact: true })
  await expect(shared).toContainText("0/2 complete")
  await expect(page.getByLabel("Counts")).toContainText("2 in flight")
  await shared.getByRole("button", { name: "Complete Implementation agent", exact: true }).click()
  await expect(shared).toContainText("1/2 complete")
  await expect(review).toBeDisabled()
  await shared.getByRole("button", { name: "Implementer 2", exact: true }).click()
  await expect(page.getByRole("complementary", { name: "Card for Implementer 2" })).toContainText("Fix a typo directly")
  await page.getByRole("button", { name: "Ask for help", exact: true }).click()
  const form = page.getByRole("form", { name: "What help or clarification does this task need?" })
  await expect(shared.getByRole("button", { name: "Complete Implementer 2", exact: true })).toBeDisabled()
  await form.getByRole("textbox").fill("Keep the same task identity.")
  await form.getByRole("button", { name: "Submit response" }).click()
  await shared.getByRole("button", { name: "Fail Implementer 2", exact: true }).click()
  await expect(shared).toContainText("error")
  await page.getByRole("button", { name: "Inspect task", exact: true }).click()
  const card = page.getByRole("complementary", { name: "Card for Fix a typo directly" })
  await expect(card).toContainText("Implementation agent: complete")
  await expect(card).toContainText("Implementer 2: error")
  await page.screenshot({ path: "test-results/shared-work.png" })
  await page.getByRole("button", { name: "Return to planning" }).click()
  for (const question of ["Who is this feature for, and what should it do?", "What should count as success, and which constraints matter?"]) {
    const questionForm = page.getByRole("form", { name: question })
    await expect(questionForm).toBeVisible({ timeout: 30000 })
    await questionForm.getByRole("textbox").fill("Proceed with the revised plan.")
    await questionForm.getByRole("button", { name: "Submit response" }).click()
  }
  await page.getByRole("button", { name: "Send to Implementation", exact: true }).click()
  await expect(page.getByRole("status")).toContainText("in Implementation", { timeout: 30000 })
  await expect(shared).toContainText("0/2 complete")
  await shared.getByRole("button", { name: "Complete Implementation agent", exact: true }).click()
  await shared.getByRole("button", { name: "Complete Implementer 2", exact: true }).click()
  await expect(shared).toContainText("2/2 complete")
  await expect(review).toBeEnabled()
  await expect(page.getByRole("status")).toContainText("in Implementation")
  await review.click()
  await expect(page.getByRole("status")).toContainText("in Code review", { timeout: 30000 })
  await expect(page.getByLabel("Counts")).toContainText("2 in flight")
  await expect(page.getByRole("alert")).toHaveCount(0)
  expect(errors).toEqual([])
})
